#!/bin/bash
# ==========================================================================
# スタジアムビジョン得点板 - デスクトップにショートカットを作る（Mac用）
#   1. ZIPから展開したファイルに付く「インターネットから来たファイル」の印を外す
#      （この印が付いたままだと、ダブルクリックしても「開けません」と止められる）
#   2. デスクトップに「得点板 管理画面」「得点板 HDMI出力」を作る
#      （別のMacで使うときも、このフォルダをコピーしてから1回実行すればよい）
# ==========================================================================
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DESKTOP="$HOME/Desktop"
MARKER='# STADIUMVISION得点板 ショートカット'

fail() {
    echo
    echo "[エラー] $1"
    exit 1
}

[ -d "$DESKTOP" ] || fail "デスクトップのフォルダが見つかりません：$DESKTOP"

# --------------------------------------------------------------------------
# 1. 「インターネットから来たファイル」の印を外す（このフォルダの中だけ）
# --------------------------------------------------------------------------
count=0
while IFS= read -r -d '' f; do
    if xattr "$f" | grep -qx 'com.apple.quarantine'; then
        xattr -d com.apple.quarantine "$f"
        count=$((count + 1))
    fi
done < <(find "$ROOT" -print0)
echo "ダブルクリックで開けるように準備しました（${count}個のファイル）"

# --------------------------------------------------------------------------
# 2. デスクトップにショートカットを作る
# --------------------------------------------------------------------------
echo "デスクトップ：$DESKTOP"
make_shortcut() {
    local name="$1" target="$ROOT/$2"
    local dest="$DESKTOP/$name.command"
    [ -f "$target" ] || fail "起動ファイルが見つかりません：$target"

    # 同じ名前の別のファイルがある場合は、上書きせずに止める
    # （このスクリプトで作ったものは、フォルダを移した後の作り直しとみなして上書きする）
    if [ -e "$dest" ] && ! grep -qF "$MARKER" "$dest"; then
        fail "デスクトップに同じ名前の別のファイルがあります（$dest）。名前を変えるか削除してから、もう一度実行してください。"
    fi

    {
        echo '#!/bin/bash'
        echo "$MARKER（「デスクトップにショートカットを作る（Mac）」で作成）"
        # フォルダ名をそのまま ' で囲んで書く（名前に ' が入っている場合は '\'' に置き換える）
        echo "TARGET='${target//\'/\'\\\'\'}'"
        echo 'if [ ! -f "$TARGET" ]; then'
        echo '    echo "[エラー] 得点板のフォルダが見つかりません（移動または削除された可能性があります）：$TARGET"'
        echo '    echo "        フォルダの中の「デスクトップにショートカットを作る（Mac）」を、もう一度実行してください。"'
        echo '    read -r -p "Enterキーを押すと閉じます" _'
        echo '    exit 1'
        echo 'fi'
        echo 'exec /bin/bash "$TARGET" "$@"'
    } > "$dest"
    chmod +x "$dest"
    echo "  作成しました：$name"
}

make_shortcut '得点板 管理画面' 'サーバー起動（Mac）.command'
make_shortcut '得点板 HDMI出力' 'HDMI出力（Mac）.command'
